def nome_voce(sv):
    parti = ["elevenlabs", sv["voce"], sv["modello"]] if sv["motore"] == "elevenlabs" else ["gratuita", sv["modello"], sv["voce"]]
    return re.sub(r"[^A-Za-z0-9_.-]+", "-", "-".join(parti))[:80]


