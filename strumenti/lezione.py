def parole_e_segni(voce):
    """Las palabras de la voz (sin marcadores) y, para cada marcador, el índice de la palabra que lo sigue."""
    parole, segni = [], {}
    for pezzo in re.split(r"(\{\{\w+\}\})", voce):
        m = SEGNO.fullmatch(pezzo)
        if m:
            segni[m.group(1)] = len(parole)
        else:
            parole += pezzo.split()
    return parole, segni


def testo_voce(voce):
    return re.sub(r"\s+", " ", SEGNO.sub("", voce)).strip()


def norma(p):
    p = unicodedata.normalize("NFKD", p.lower())
    return "".join(c for c in p if c.isalnum())


def tempi_parole(parole, riconosciute):
    """Inicio y fin de cada palabra del guion a partir de las reconocidas (faster-whisper): alineación por texto, huecos por interpolación."""
    a = [norma(p) for p in parole]
    b = [norma(r["w"]) for r in riconosciute]
    tempi = [None] * len(parole)
    for blocco in SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
        for k in range(blocco.size):
            r = riconosciute[blocco.b + k]
            tempi[blocco.a + k] = [r["inizio"], r["fine"]]
    noti = [i for i, t in enumerate(tempi) if t]
    if not noti:
        return None
    for i in range(len(tempi)):
        if tempi[i]:
            continue
        prima = max((j for j in noti if j < i), default=None)
        dopo = min((j for j in noti if j > i), default=None)
        if prima is None:
            tempi[i] = [tempi[dopo][0], tempi[dopo][0]]
        elif dopo is None:
            tempi[i] = [tempi[prima][1], tempi[prima][1]]
        else:
            t0, t1 = tempi[prima][1], tempi[dopo][0]
            k = (i - prima) / (dopo - prima)
            tempi[i] = [t0 + (t1 - t0) * k, t0 + (t1 - t0) * k]
    return tempi


def pezzi_sottotitoli(parole, tempi, max_parole=11, max_car=64):
    pezzi, cur = [], []
    for i, p in enumerate(parole):
        cur.append(i)
        testo = " ".join(parole[j] for j in cur)
        fine_frase = p[-1] in ".?!:;," and len(cur) >= 5
        if len(cur) >= max_parole or len(testo) >= max_car or fine_frase or i == len(parole) - 1:
            pezzi.append(cur)
            cur = []
    out = []
    for k, idx in enumerate(pezzi):
        da = tempi[idx[0]][0]
        a = tempi[pezzi[k + 1][0]][0] if k + 1 < len(pezzi) else tempi[idx[-1]][1] + 0.3
        out.append({"da": da, "a": a, "testo": " ".join(parole[j] for j in idx)})
    return out


