def impronta(*parti):
    import hashlib

    return hashlib.sha1(json.dumps(parti, ensure_ascii=False).encode("utf-8")).hexdigest()[:16]


def voce(slug, tappa, seme=7, motore=None, voce_id=None, modello=None, solo_verifica=False):
    """Voz de cada escena y tiempos palabra por palabra. Las escenas ya hechas con el mismo texto y la misma voz no se rehacen: para
    rehacer una, borra voce/<id>.voce.json (con `--seme N` vuelve a empezar desde otra semilla)."""
    base, lingua, f_copione, lavoro = cartelle(slug, tappa)
    c, sv = leggi(f_copione), scelta_voce(lingua, motore, voce_id, modello)
    cartella = lavoro / "voce" / nome_voce(sv)  # una carpeta por voz: se vuelve a una voz ya hecha sin regenerarla
    if not solo_verifica and (sv["motore"] == "elevenlabs" or (Path(sv["python"]).exists() and sv["modello"] in sv["installati"])):
        cartella.mkdir(parents=True, exist_ok=True)  # solo cuando se genera de verdad: sin carpetas vacías por los controles
    scene = [{"id": s["id"], "testo": testo_voce(s["voce"]), "wav": str(cartella / f"{s['id']}.wav"),
              "parole": str(cartella / f"{s['id']}.parole.json")} for s in c["scene"]]
    if sv["motore"] == "elevenlabs":
        riassunto = voce_elevenlabs(sv, lingua, scene, cartella, seme, solo_verifica)
        if solo_verifica:
            return
    else:
        if not Path(sv["python"]).exists():
            print(f"falta el entorno de la voz gratuita ({sv['python']}): lo crea la instalación (installa.ps1 / installa.sh, "
                  "ver docs/lezioni.md); o usa ElevenLabs")
            sys.exit(3)
        if sv["modello"] not in sv["installati"]:
            print(f"la voz {NOMI_VOCE.get(sv['modello'], sv['modello'])} no está instalada en el entorno de la voz "
                  f"(hay: {', '.join(NOMI_VOCE.get(x, x) for x in sv['installati'] if x != 'whisper') or 'ninguna'}): vuelve a lanzar la instalación "
                  "o elige otra voz")
            sys.exit(3)
        if solo_verifica:
            print(f"voz gratuita {NOMI_VOCE.get(sv['modello'], sv['modello'])} · {sv['voce']} ({lingua}): en el ordenador, sin coste · "
                  f"control con Whisper {sv['whisper']}")
            return
        incarico = {"modello": sv["modello"], "voce": sv["voce"], "lingua": lingua, "whisper": sv["whisper"], "pronuncia": c.get("pronuncia") or {},
                    "soglia": sv["soglia"], "tentativi": sv["tentativi"], "seme": seme, "scene": scene}
        f = cartella / "incarico.json"
        scrivi(f, incarico)
        subprocess.run([sv["python"], str(Path(__file__).resolve().parent / "voce_locale.py"), str(f)], check=True)
