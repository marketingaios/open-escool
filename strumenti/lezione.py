def durata_wav(f):
    with wave.open(str(f)) as w:
        return w.getnframes() / w.getframerate()


def piano(slug, tappa, stima=False):
    base, lingua, f_copione, lavoro = cartelle(slug, tappa)
    c = leggi(f_copione)
    cfg = leggi(RADICE / "config.json", {}) or {}
    es = leggi(RADICE / "config.esempio.json", {}) or {}
    colori = {**(es.get("colori") or {}), **(cfg.get("colori") or {})}
    et = ETICHETTE.get(lingua, ETICHETTE["it"])
    scene, sottotitoli, t = [], [], 0.0
    for s in c["scene"]:
        parole, segni = parole_e_segni(s["voce"])
        f_voce, f_tempi = cartella_voce(lavoro) / f"{s['id']}.wav", cartella_voce(lavoro) / f"{s['id']}.parole.json"
        if stima or not f_voce.exists():
            if not stima:
                sys.exit(f"falta la voz de «{s['id']}»: lanza antes el paso voce, o piano --stima")
            dur = len(parole) / PAROLE_AL_SECONDO
            tempi = [[i / PAROLE_AL_SECONDO, (i + 0.8) / PAROLE_AL_SECONDO] for i in range(len(parole))]
        else:
            dur = durata_wav(f_voce)
            tempi = tempi_parole(parole, leggi(f_tempi, []) or []) or [[dur * i / len(parole), dur * (i + 1) / len(parole)] for i in range(len(parole))]
        lungo = PRIMA + dur + DOPO + (CODA if s is c["scene"][-1] else 0)
        m = {nome: max(0, round((PRIMA + tempi[min(i, len(tempi) - 1)][0] - ANTICIPO) * FPS)) for nome, i in segni.items()}
        da_f, durata_f = round(t * FPS), round((t + lungo) * FPS) - round(t * FPS)
        scene.append({"id": s["id"], "tipo": s["tipo"], "passo": s.get("passo", 0), "da_f": da_f, "durata_f": durata_f, "m": m, "schermo": s["schermo"],
                      "voce_s": round(t + PRIMA, 3), "voce_dur": round(dur, 3)})
        for p in pezzi_sottotitoli(parole, tempi):
            sottotitoli.append({"da_f": round((t + PRIMA + p["da"]) * FPS), "a_f": round((t + PRIMA + p["a"]) * FPS), "testo": p["testo"]})
        t += lungo
    v = leggi(lavoro / "voce.json", {}) or {}
    p = {"fps": FPS, "durata_f": round(t * FPS), "stimato": bool(stima), "lingua": lingua, "voce": "" if stima else v.get("etichetta") or f"{v.get('modello', '')} {v.get('voce', '')}".strip(),
         "voce_info": {} if stima else {x: v.get(x) for x in ("motore", "modello", "voce", "voce_id", "piano", "gratuito") if v.get(x) is not None}, "marchio": cfg.get("nome") or es.get("nome") or "Open Escool", "percorso": c.get("percorso", ""),
         "titolo": c["titolo"], "tappa": tappa, "etichetta_passi": et["passi"], "crediti": et["crediti"], "passi": c["passi"],
         "tema": {"acc": colori.get("primario", "#AFF320")} if colori.get("primario") else {}, "scene": scene, "sottotitoli": sottotitoli}
    scrivi(lavoro / "piano.json", p)
    print(f"plan: {len(scene)} escenas, {mmss(t)} ({'estimado' if stima else 'de la voz'}) → {lavoro / 'piano.json'}")
    return p


