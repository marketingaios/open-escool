def cartella_pubblica(lavoro):
    pub = lavoro / "public"
    pub.mkdir(exist_ok=True)
    for nome in ("font", "marca"):
        dest, sorgente = pub / nome, LEZIONE / "public" / nome
        if dest.is_symlink() and Path(os.readlink(dest)) != sorgente:  # carpeta movida o copia distinta: se rehace
            dest.unlink()
        if not dest.exists():
            try:
                dest.symlink_to(sorgente, target_is_directory=True)
            except OSError:  # Windows sin «modo de desarrollador» no crea enlaces: se copia (pocos archivos)
                shutil.copytree(sorgente, dest, dirs_exist_ok=True)
    shutil.copy(lavoro / "piano.json", pub / "piano.json")
    return pub


def remotion(lavoro, *argomenti):
    cli = LEZIONE / "node_modules" / "@remotion" / "cli" / "remotion-cli.js"
    if not cli.exists():
        sys.exit("falta Remotion: en la carpeta lezione/ lanza `npm install`")
    extra = []
    base = LEZIONE / "node_modules" / ".remotion" / "chrome-headless-shell"
    chrome = list(base.glob("*/*/chrome-headless-shell")) + list(base.glob("*/*/chrome-headless-shell.exe"))
    if chrome:
        extra.append(f"--browser-executable={chrome[0]}")
    pub = cartella_pubblica(lavoro)
    subprocess.run(["node", str(cli), *argomenti, f"--public-dir={pub}", "--bundle-cache=false", "--log=error", *extra], cwd=LEZIONE, check=True)


def ffmpeg(*a):
    subprocess.run(["ffmpeg", "-v", "error", "-y", *a], check=True)


def audio(lavoro, p):
    """La voz de cada escena en su sitio, sobre silencio; luego -16 LUFS sin limitadores fuertes."""
    voce = cartella_voce(lavoro)
    lista, entrate = [], []
    for i, s in enumerate(p["scene"]):
        lista += ["-i", str(voce / f"{s['id']}.wav")]
        ms = round(s["voce_s"] * 1000)
        entrate.append(f"[{i}:a]aresample={SR},aformat=channel_layouts=mono,adelay={ms}|{ms}[a{i}]")
    n = len(p["scene"])
    filtro = ";".join(entrate) + ";" + "".join(f"[a{i}]" for i in range(n)) + f"amix=inputs={n}:normalize=0:duration=longest,apad,atrim=0:{p['durata_f'] / FPS:.3f},loudnorm=I=-16:TP=-1.5:LRA=11[out]"
    uscita = lavoro / "voce.m4a"
    ffmpeg(*lista, "-filter_complex", filtro, "-map", "[out]", "-ar", str(SR), "-c:a", "aac", "-b:a", "160k", str(uscita))
    return uscita


def video(slug, tappa):
    base, lingua, f_copione, lavoro = cartelle(slug, tappa)
    p = leggi(lavoro / "piano.json")
    if not p:
        sys.exit("falta el plan: lanza antes el paso piano")
    muto = lavoro / "muto.mp4"
    remotion(lavoro, "render", "src/index.ts", "Lezione", str(muto), "--codec=h264", "--crf=20", "--pixel-format=yuv420p", "--image-format=jpeg",
             "--jpeg-quality=92", "--concurrency=4", "--muted")
    dest = PERCORSI / slug / "lezioni"
    dest.mkdir(exist_ok=True)
    finale = dest / f"t{tappa}.mp4"
    if p.get("stimato") or not cartella_voce(lavoro).exists():
        shutil.copy(muto, finale)
    else:
        ffmpeg("-i", str(muto), "-i", str(audio(lavoro, p)), "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "copy", "-movflags", "+faststart", "-shortest", str(finale))
    # portada: con el título ya escrito
    s0 = p["scene"][0]
    remotion(lavoro, "still", "src/index.ts", "Lezione", str(dest / f"t{tappa}.jpg"), f"--frame={s0['da_f'] + min(s0['durata_f'] - 1, 75)}", "--image-format=jpeg", "--jpeg-quality=88")
    print(f"vídeo: {finale} ({mmss(p['durata_f'] / FPS)})")


