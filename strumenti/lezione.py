def scelta_voce(lingua, motore=None, voce_id=None, modello=None):
    """La voz de la lección: la de Ajustes (config.json → lezioni) o la pedida para esta lección (--motore, --id, --modello)."""
    imp = impostazioni_lezioni()
    motore = motore or imp.get("motore") or "gratuita"
    if motore == "elevenlabs":
        import elevenlabs

        e = imp.get("elevenlabs") or {}
        vid = voce_id or ((e.get("voci") or {}).get(lingua) or "").strip() or (e.get("voce") or "").strip()
        if not vid:
            sys.exit("falta el ID de la voz de ElevenLabs: Ajustes → Voz de las lecciones, o --id <ID>")
        regole = {"stability": e.get("stabilita"), "similarity_boost": e.get("somiglianza"), "style": e.get("stile"), "speed": e.get("velocita")}
        return {"motore": "elevenlabs", "voce": vid, "modello": modello or e.get("modello") or elevenlabs.MODELLO_BASE,
                "impostazioni": {k: float(v) for k, v in regole.items() if v is not None}}
    from comune import VOCI_BASE, mac_apple, modello_gratuito, moduli_voce, python_voce

    v = imp.get("voce") or {}
    py = python_voce(v.get("python") or "")
    installati = moduli_voce(py)
    mod = modello_gratuito(modello or v.get("modello"), installati, lingua)
    voci = (v.get("voci") or {}).get(mod) or {}  # una voz por idioma y por modelo: {"supertonic": {"it": "F2"}}
    # Whisper da los tiempos de las palabras y hace el control: «medium» en Apple Silicon; «small» en cualquier portátil (2-3 veces más rápido)
    whisper = v.get("whisper") or ("medium" if mac_apple() else "small")
    return {"motore": "gratuita", "python": str(py), "modello": mod, "voce": voce_id or voci.get(lingua) or VOCI_BASE.get(mod, {}).get(lingua) or "base",
            "whisper": whisper, "soglia": v.get("soglia", 0.9), "tentativi": v.get("tentativi", 4), "installati": sorted(installati)}


