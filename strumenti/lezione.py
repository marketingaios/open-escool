def unisci(a, b):
    """b encima de a, también dentro de los diccionarios anidados (config.json encima de config.esempio.json)."""
    out = dict(a)
    for k, v in (b or {}).items():
        out[k] = unisci(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


