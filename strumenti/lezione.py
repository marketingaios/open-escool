def voce_lezione(lez, lingua):
    """La lección como vídeo de la etapa en percorso.json (principal; los vídeos de YouTube quedan como alternativas)."""
    et = ETICHETTE.get(lingua, ETICHETTE["it"])
    scene, fonti = lez.get("scene", []), sorted({f for s in lez.get("scene", []) for f in s.get("fonti", [])})
    vi = lez.get("voce_info") or {}
    # la etiqueta de la voz gratuita se rehace en el idioma de la ruta (las lecciones antiguas la guardaban en italiano)
    voce = (et["voce_gratuita"].format(nome=NOMI_VOCE.get(vi["modello"], vi["modello"])) if vi.get("motore") == "gratuita" and vi.get("modello")
            else lez.get("voce", ""))
    return {
        "id": f"lezione-t{lez['tappa']}", "tipo": "lezione", "ruolo": "principale", "titolo": lez["titolo"], "canale": et["canale"], "lingua": lingua,
        "pubblicato": lez.get("creata"), "durata_s": lez["durata_s"], "file": lez["file"], "copertina": lez["copertina"],
        "inizio": "0:00", "fine": mmss(lez["durata_s"]),
        "riassunto": " ".join(s["testo"] for s in scene[:2])[:600],
        "punti": [{"minuto": mmss(s["inizio"]), "testo": s["titolo"]} for s in scene if s.get("titolo")],
        "attenzione": [],
        "perche": et["perche"].format(n=len(fonti), data=lez.get("controllata")),
        "punteggio": "lezione", "voce": voce,
        **({"avviso_voce": av} if (av := avviso_voce(lez.get("voce_info") or {}, lingua)) else {}),
    }


def metti_lezioni(slug):
    """Vuelve a poner en percorso.json todas las lecciones de lezioni/t<N>.json: también la llama costruisci.py, así reconstruir la
    ruta no las pierde. El vídeo principal de antes pasa a ser una alternativa."""
    f_p = PERCORSI / slug / "percorso.json"
    perc = leggi(f_p)
    if not perc:
        return 0
    lingua = perc.get("lingua_video") or "it"
    n = 0
    for f in sorted((PERCORSI / slug / "lezioni").glob("t*.json")):
        lez = leggi(f)
        t = next((x for x in perc["tappe"] if x["n"] == lez.get("tappa")), None) if lez else None
        if not t:
            continue
        v = voce_lezione(lez, lingua)
        altri = [x for x in t.get("video", []) if x.get("id") != v["id"]]
        for x in altri:
            if x.get("ruolo") == "principale":
                x["ruolo"] = "alternativo"
        t["video"] = [v] + altri
        t["buco"] = None
        t["minuti_video"] = max(1, round(lez["durata_s"] / 60))
        n += 1
    if n:
        perc["durata_min"] = sum(t.get("minuti_video") or 0 for t in perc["tappe"])
        scrivi(f_p, perc)
    return n


def pubblica(slug, tappa):
    """Escribe lezioni/t<N>.json (texto exacto y tiempos: el chat lo usa como transcripción, la página como ficha) y pone la
    lección como vídeo principal de la etapa."""
    base, lingua, f_copione, lavoro = cartelle(slug, tappa)
    c, p = leggi(f_copione), leggi(lavoro / "piano.json")
    if not p or p.get("stimato"):
        sys.exit("hacen falta el plan de la voz real (paso piano sin --stima) y el vídeo")
    dest = PERCORSI / slug / "lezioni"
    if not (dest / f"t{tappa}.mp4").exists():
        sys.exit("falta el vídeo: lanza antes el paso video")
    dur = p["durata_f"] / FPS
    scene = []
    for s, sp in zip(c["scene"], p["scene"]):
        scene.append({"id": s["id"], "titolo": s["schermo"].get("titolo", ""), "inizio": round(sp["da_f"] / FPS, 1), "fine": round((sp["da_f"] + sp["durata_f"]) / FPS, 1),
                      "testo": testo_voce(s["voce"]), "fonti": s.get("fonti", []), "consiglio": bool(s.get("consiglio"))})
    frasi = [{"inizio": round(x["da_f"] / FPS, 1), "testo": x["testo"]} for x in p["sottotitoli"]]
    scrivi(dest / f"t{tappa}.json", {"tappa": tappa, "lingua": lingua, "titolo": c["titolo"], "durata_s": round(dur), "file": f"lezioni/t{tappa}.mp4",
                                     "copertina": f"lezioni/t{tappa}.jpg", "controllata": c.get("controllata"), "creata": date.today().isoformat(),
                                     "voce": p.get("voce", ""), "voce_info": p.get("voce_info") or {}, "scene": scene, "frasi": frasi})
    metti_lezioni(slug)
    print(f"publicada: etapa {tappa} de {slug}, {mmss(dur)}; los vídeos de YouTube quedan como alternativas")


def main():
    a = sys.argv[1:]
    if len(a) < 3:
        sys.exit(__doc__)
    slug, tappa, passo = a[0], int(a[1]), a[2]
    opz = lambda nome: a[a.index(nome) + 1] if nome in a and a.index(nome) + 1 < len(a) else None  # noqa: E731
    if passo == "voce":
        voce(slug, tappa, int(opz("--seme") or 7), opz("--motore"), opz("--id"), opz("--modello"), "--verifica" in a)
    elif passo == "piano":
        piano(slug, tappa, stima="--stima" in a)
    elif passo == "video":
        video(slug, tappa)
    elif passo == "fermi":
        fermi(slug, tappa, [float(x) for x in a[3].split(",")])
    elif passo == "pubblica":
        pubblica(slug, tappa)
    else:
        sys.exit(__doc__)


